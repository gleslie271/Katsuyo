"""Build the JLPT word list in katsuyo.html from a JLPT vocabulary sheet and the JMdict dictionary.

The sheet gives each word's reading, spelling and JLPT level. JMdict (jmdict-simplified's English JSON) gives its
word type and English meaning. Words the drill can't conjugate (adverbs, expressions, irregular verb classes…) are
left out. The result replaces the block between the JLPT markers in katsuyo.html.

Usage:  python make_jlpt.py vocab.csv jmdict-eng.json
  vocab.csv    the sheet's vocab tab as CSV: reading, word, level (N5–N1)
  jmdict-eng   jmdict-eng-*.json from https://github.com/scriptin/jmdict-simplified/releases
"""
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

PAGE = Path(__file__).resolve().parent / 'katsuyo.html'
START = '// ---------- JLPT words (generated by make_jlpt.py; do not edit by hand) ----------\n'
END = '// ---------- end of JLPT words ----------\n'

# JMdict part-of-speech tags → the drill's word classes
GODAN = {'v5u': 'う', 'v5k': 'く', 'v5g': 'ぐ', 'v5s': 'す', 'v5t': 'つ', 'v5n': 'ぬ', 'v5b': 'ぶ', 'v5m': 'む', 'v5r': 'る', 'v5k-s': 'く'}
# Verb classes the engine doesn't model (くださる, 問う, 愛する, 信ずる, くれる, classical verbs…): such words are skipped
IRREGULAR = re.compile(r'^(v5aru|v5u-s|v5r-i|v5uru|vs-s|vs-c|vz|v1-s|vr|vn|v2.*|v4.*)$')
NOUN = {'n', 'pn'}
CODE = {'godan': 'g', 'ichidan': 'i', 'suru': 's', 'kuru': 'k', 'iadj': 'a', 'naadj': 'n', 'noun': 'o'}
BAD_CHARS = set('〜～…・()（）、, /／')


def has_kanji(s):
    return any('一' <= ch <= '鿿' or ch == '々' for ch in s)


def classify(pos):
    """The drill class for one sense's parts of speech, with flags, or None. 'skip' for verbs it can't conjugate."""
    if any(IRREGULAR.match(p) for p in pos):
        return 'skip', {}
    for p in pos:
        if p in GODAN:
            return 'godan', {'k': p == 'v5k-s', 'end': GODAN[p]}
        if p == 'v1':
            return 'ichidan', {}
        if p == 'vk':
            return 'kuru', {}
        if p == 'vs-i':
            return 'suru', {}
    if 'adj-ix' in pos:
        return 'iadj', {'y': True}
    if 'adj-i' in pos:
        return 'iadj', {}
    if 'adj-na' in pos:
        return 'naadj', {}
    if NOUN & set(pos):
        return 'noun', {}
    return None, {}


def meaning(sense, verb):
    """Up to three English glosses of a sense, kept short: "to write; to compose"."""
    gl = [g['text'] for g in sense['gloss'] if g.get('lang') == 'eng' and g.get('type') in (None, 'fig')]
    gl = [re.sub(r'[|`\\]|\$\{', '', g).strip() for g in gl if g.strip()]
    # Long glosses lose their bracketed notes: "kindergarten (in Japan, non-compulsory…)" → "kindergarten"
    gl = [re.sub(r'\s*\([^)]*\)', '', g).strip() if len(g) > 40 else g for g in gl]
    if verb:
        gl = [g if g.startswith('to ') else 'to ' + g for g in gl]
    else:
        gl = [g for g in gl if not g.startswith('to ')]        # an adjective or noun glossed as a verb ("to be stumped") reads wrong
    out = gl[:1]
    for g in gl[1:3]:
        if len('; '.join(out + [g])) > 40:
            break
        out.append(g)
    return '; '.join(out)


def main(csv_path, dict_path):
    page = PAGE.read_text(encoding='utf-8')
    # The hand-picked starter words: [kanji, reading, meaning, class…]
    words_block = page[page.index('const WORDS = ['):page.index('].map(([k, r, m, c, f])')]
    core = re.findall(r"\['([^']+)','([^']+)','[^']*','(\w+)'", words_block)
    core_exact = {(k, r) for k, r, c in core}
    core_kana = {(r, c): k for k, r, c in core if k == r}      # starter words written in kana (いい), for sheet spellings in kanji (良い)
    core_kanji = {k for k, r, c in core if has_kanji(k)}       # 行く read ゆく or 本当 read ほんと would look like repeats of a starter word

    jm = json.load(open(dict_path, encoding='utf-8'))['words']
    by_kanji, by_kana = defaultdict(list), defaultdict(list)
    for e in jm:
        for k in e['kanji']:
            by_kanji[k['text']].append(e)
        for k in e['kana']:
            by_kana[k['text']].append(e)

    rows = list(csv.reader(open(csv_path, encoding='utf-8')))[1:]
    rows = [[x.strip() for x in r[:3]] for r in rows if len(r) >= 3]
    rows.sort(key=lambda r: -int(r[2][1]) if re.fullmatch(r'N[1-5]', r[2]) else 0)  # N5 first, so a word keeps its easiest level

    core_level, out, seen, stats = {}, [], set(), defaultdict(int)
    for r0, k0, lvl in rows:
        if not re.fullmatch(r'N[1-5]', lvl) or not r0 or not k0 or BAD_CHARS & set(k0 + r0):
            stats['unusable row'] += 1
            continue
        lv = int(lvl[1])
        # Dictionary entries for this spelling and reading, most common first
        if has_kanji(k0):
            cands = [e for e in by_kanji.get(k0, []) if any(
                kn['text'] == r0 and ('*' in kn['appliesToKanji'] or k0 in kn['appliesToKanji']) for kn in e['kana'])]
        else:
            cands = by_kana.get(k0, []) or by_kana.get(r0, [])
        if not cands:
            stats['not in JMdict'] += 1
            continue
        common = lambda e: any(x['common'] for x in e['kanji'] if x['text'] == k0) or any(x['common'] for x in e['kana'] if x['text'] == r0)
        cands = sorted(cands, key=lambda e: not common(e))

        found = None
        for e in cands:
            senses = [s for s in e['sense']
                      if (not has_kanji(k0) or '*' in s['appliesToKanji'] or k0 in s['appliesToKanji'])
                      and ('*' in s['appliesToKana'] or r0 in s['appliesToKana'])]
            for s in senses:                                    # the first sense that names a class the drill can use
                c, flags = classify(s['partOfSpeech'])
                if c:
                    found = (c, flags, s, senses[0])
                    break
            if found:
                break
        if not found or found[0] == 'skip':
            stats['skipped (irregular verb)' if found else 'not conjugatable (adverb, expression…)'] += 1
            continue
        c, flags, sense, first = found

        # Usually written in kana (居る, 有る, 為る): show the kana
        k = r0 if not has_kanji(k0) or 'uk' in first['misc'] else k0
        verb = c in ('godan', 'ichidan', 'suru', 'kuru')
        # The engine changes the word's ending, so the reading must end the way its class says
        ending = {'godan': flags.pop('end', None), 'ichidan': 'る', 'suru': 'する', 'kuru': 'くる', 'iadj': 'いい' if flags.get('y') else 'い'}.get(c)
        if ending and not r0.endswith(ending):
            stats['bad ending'] += 1
            continue
        # …and the kanji spelling must end in the same kana, or the kana spelling is used instead
        if ending and c != 'kuru' and k[-1] != r0[-1]:
            k = r0
        fl = ''.join(f for f, on in flags.items() if on)
        if c == 'naadj' and r0.endswith('い'):
            fl += 'e'                                           # a な-adjective that ends in い (きれい)
        if verb and 'vi' in sense['partOfSpeech'] and 'vt' not in sense['partOfSpeech']:
            fl += 'v'                                           # intransitive: English passives read "have someone … on me"
        if c == 'suru':
            fl += 'l'                                           # 恋する, 値する: 恋できる isn't natural, so core tense forms only

        if (k, r0) in core_exact or (r0, c) in core_kana:
            ck = k if (k, r0) in core_exact else core_kana[(r0, c)]
            core_level.setdefault(ck, lv)
            stats['already a starter word'] += 1
            continue
        if (k, r0, c) in seen or k in core_kanji:
            stats['duplicate'] += 1
            continue
        seen.add((k, r0, c))
        m = meaning(sense, verb)
        if not m:
            stats['no English meaning'] += 1
            continue
        out.append((k, r0, m, c, lv, fl))
        stats[f'added {c}'] += 1

    lines = [f"{'' if k == r else k}|{r}|{m}|{CODE[c]}|{lv}|{fl}".rstrip('|') for k, r, m, c, lv, fl in out]
    block = (START +
             '// Words from the JLPT vocabulary lists (N5–N1). Meanings and word types: JMdict, © EDRDG, CC BY-SA 4.0.\n'
             '// CORE_LEVEL gives the hand-picked starter words their JLPT level.\n'
             '// JLPT_DATA, one word per line: kanji (empty when written in kana)|reading|meaning|class|level|flags\n'
             '// Classes: g godan, i ichidan, s する, k 来る, a い-adjective, n な-adjective, o noun.\n'
             '// Flags: k 行く-type て-form, y conjugates from よい, e な-adjective ending in い, v intransitive, l core forms only.\n'
             f'const CORE_LEVEL = {json.dumps(core_level, ensure_ascii=False, separators=(",", ":"))};\n'
             'const JLPT_DATA = `\n' + '\n'.join(lines) + '\n`;\n' + END)
    if START in page:
        page = page[:page.index(START)] + block + page[page.index(END) + len(END):]
    else:
        at = page.index('// ---------- Conjugation engine ----------')
        page = page[:at] + block + '\n' + page[at:]
    PAGE.write_text(page, encoding='utf-8', newline='\n')

    for k, v in sorted(stats.items()):
        print(f'{k}: {v}')
    per = defaultdict(lambda: defaultdict(int))
    for k, r, m, c, lv, fl in out:
        per[lv][c] += 1
    for lv in sorted(per, reverse=True):
        print(f'N{lv}: ' + ', '.join(f'{c} {n}' for c, n in sorted(per[lv].items())) + f'  (total {sum(per[lv].values())})')
    print(f'starter words with a level: {len(core_level)} of {len(core)}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main(*sys.argv[1:3])
